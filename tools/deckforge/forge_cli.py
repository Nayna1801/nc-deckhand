"""deckforge: herramienta para analizar, optimizar y comparar mazos del Cyberpunk TCG.

Árbitro (reglas) + red de sinergias + simulador de partidas + optimizador. Solo biblioteca estándar.
Uso:  python tools/deckforge/forge.py <comando> --help      (README.md explica el flujo completo)
"""
import argparse
import sys

from deckio import DEFAULT_FIELD, DEFAULT_PROCS, HERE, OUT
from forge_basic import cmd_check, cmd_export, cmd_import_text, cmd_score, cmd_validate
from forge_graph import cmd_graph, cmd_learn, cmd_reason, cmd_trios
from forge_search import cmd_match, cmd_optimize, cmd_search, cmd_sideboard
from forge_selftest import cmd_selftest
from humanlog import DATA_DIR as HUMAN_DIR, cmd_humanlog
from forge_sim import (
    cmd_evolve, cmd_explain, cmd_gauntlet, cmd_hands, cmd_matrix, cmd_playbook, cmd_replay, cmd_robust, cmd_sim,
    cmd_valfn, set_deep,
)


def _basic_commands(sub):
    """Comandos sencillos: check, validate, import-text, export y score."""
    p = sub.add_parser('check', help='audita el catálogo: cartas nuevas sin anotar y mecánicas desconocidas')
    p.set_defaults(f=cmd_check)
    p = sub.add_parser('validate', help='árbitro: comprueba que un mazo JSON es legal')
    p.add_argument('deck')
    p.set_defaults(f=cmd_validate)
    p = sub.add_parser('import-text', help='convierte el texto exportado por la web a mazo JSON')
    p.add_argument('text')
    p.add_argument('--out')
    p.set_defaults(f=cmd_import_text)
    p = sub.add_parser('export', help='convierte un mazo JSON al texto que acepta «Importar» de la web')
    p.add_argument('deck')
    p.add_argument('--out')
    p.set_defaults(f=cmd_export)
    p = sub.add_parser('score', help='puntúa con la red de sinergias y muestra enlaces, nodos centrales y counters')
    p.add_argument('deck')
    p.add_argument('--top', type=int, default=12)
    p.set_defaults(f=cmd_score)


def _sim_commands(sub):
    """Comandos de simulación: sim, gauntlet, evolve, valfn, robust, hands, explain y matrix."""
    p = sub.add_parser('sim', help='enfrenta dos mazos (partidas completas)')
    p.add_argument('deck_a')
    p.add_argument('deck_b')
    p.add_argument('--games', type=int, default=400)
    p.add_argument('--seed', type=int, default=1)
    p.set_defaults(f=cmd_sim)
    p = sub.add_parser('gauntlet', help='enfrenta un mazo contra un campo de mazos')
    p.add_argument('deck')
    p.add_argument('--field', default=str(DEFAULT_FIELD), help='JSON de campo o carpeta de mazos JSON')
    p.add_argument('--games', type=int, default=200)
    p.add_argument('--seed', type=int, default=5)
    p.add_argument('--procs', type=int, default=DEFAULT_PROCS)
    p.add_argument('--err', type=float, default=0.0, help='probabilidad de fallo humano por decisión del mazo propio (0-1)')
    p.add_argument('--err-rival', type=float, default=0.0, help='idem para los rivales')
    p.set_defaults(f=cmd_gauntlet)
    p = sub.add_parser('evolve', help='auto-mejora: la IA aprende a jugar mejor y se busca el mejor mazo por situación')
    p.add_argument('--cycles', type=int, default=1, help='vueltas (0 = hasta agotar --hours o hasta crear out/evolve.STOP)')
    p.add_argument('--hours', type=float, default=0.0, help='tiempo máximo en horas')
    p.add_argument('--procs', type=int, default=DEFAULT_PROCS)
    p.add_argument('--quick', action='store_true', help='vuelta diminuta para comprobar que funciona (no adopta redes)')
    p.set_defaults(f=cmd_evolve)
    p = sub.add_parser('valfn', help='valoración de posición aprendida de partidas: collect | train | compare')
    p.add_argument('action', choices=('collect', 'train', 'compare'))
    p.add_argument('--fast-games', type=int, default=20000, help='collect: partidas rápidas (sin previsión)')
    p.add_argument('--deep-games', type=int, default=1500, help='collect: partidas con previsión')
    p.add_argument('--epochs', type=int, default=60)
    p.add_argument('--out', help='train: dónde guardar la red (por defecto data/valfn.json, la vigente)')
    p.add_argument('--data', help='collect/train: fichero de posiciones (por defecto out/valfn_data.json)')
    p.add_argument('--vf', default='hand', help='collect: con qué valoración juegan las partidas (hand | action@ruta)')
    p.add_argument('--variant', default='learned', help='compare: valoración del lado A: learned | action | action@ruta-de-red')
    p.add_argument('--other', default='hand', help='compare: valoración del lado B (por defecto la fórmula a mano)')
    p.add_argument('--games', type=int, default=200, help='compare: partidas por pareja de mazos')
    p.add_argument('--deck', default=str(HERE / 'decks' / 'mejor_goro_wakako_v.json'))
    p.add_argument('--field', default=str(HERE / 'meta'))
    p.add_argument('--procs', type=int, default=DEFAULT_PROCS)
    p.set_defaults(f=cmd_valfn)
    p = sub.add_parser('robust', help='robustez del mazo: cuánto baja el resultado si el piloto falla decisiones')
    p.add_argument('deck')
    p.add_argument('--field', default=str(DEFAULT_FIELD), help='JSON de campo o carpeta de mazos JSON')
    p.add_argument('--games', type=int, default=150)
    p.add_argument('--seed', type=int, default=5)
    p.add_argument('--procs', type=int, default=DEFAULT_PROCS)
    p.add_argument('--levels', default='0,0.1,0.2,0.3', help='niveles de fallo separados por comas')
    p.add_argument('--mode', choices=('all', 'solo', 'both'), default='all')
    p.add_argument('--out')
    p.set_defaults(f=cmd_robust)
    p = sub.add_parser('hands', help='manos iniciales y desarrollo de los primeros turnos (¿se atasca?)')
    p.add_argument('deck')
    p.add_argument('--n', type=int, default=400)
    p.set_defaults(f=cmd_hands)
    p = sub.add_parser('explain', help='POR QUÉ gana o pierde: factores, fuentes, cartas, sinergias y cruces medidos en partidas')
    p.add_argument('deck')
    p.add_argument('--field', default=str(DEFAULT_FIELD), help='JSON de campo o carpeta de mazos JSON')
    p.add_argument('--games', type=int, default=400, help='partidas por rival (más = menos ruido)')
    p.add_argument('--seed', type=int, default=5)
    p.add_argument('--top', type=int, default=8)
    p.add_argument('--procs', type=int, default=DEFAULT_PROCS)
    p.add_argument('--out', help='guardar el informe en un fichero de texto')
    p.set_defaults(f=cmd_explain)
    p = sub.add_parser('playbook', help='guía de juego: victorias por rival, mano y situación, y qué jugar o vender en cada turno')
    p.add_argument('deck')
    p.add_argument('--field', default=str(DEFAULT_FIELD), help='JSON de campo o carpeta de mazos JSON')
    p.add_argument('--games', type=int, default=300, help='partidas por rival (más = menos ruido)')
    p.add_argument('--seed', type=int, default=5)
    p.add_argument('--procs', type=int, default=2)
    p.add_argument('--rival', help='analizar solo las partidas contra los rivales cuyo nombre contenga este texto (p. ej. «River»)')
    p.add_argument('--per-rival', action='store_true', help='una guía completa por cada rival del campo')
    p.add_argument('--out', help='guardar la guía en un fichero de texto')
    p.set_defaults(f=cmd_playbook)
    p = sub.add_parser('replay', help='graba partidas completas paso a paso (tablero y acciones) para verlas en la página visor')
    p.add_argument('deck_a')
    p.add_argument('deck_b')
    p.add_argument('--games', type=int, default=2, help='partidas (se alterna quién empieza)')
    p.add_argument('--seed', type=int, default=1)
    p.add_argument('--fast', action='store_true', help='piloto sin previsión (más rápido, juega peor)')
    p.add_argument('--append', action='store_true', help='añadir al fichero en vez de sustituirlo')
    p.add_argument('--out', default=str(HERE / 'out' / 'replay.json'))
    p.set_defaults(f=cmd_replay)
    p = sub.add_parser('humanlog', help='compara tus partidas del Laboratorio (jugar contra el piloto) con lo que habría hecho el piloto')
    p.add_argument('--dir', default=str(HUMAN_DIR), help='carpeta con las partidas guardadas')
    p.add_argument('--sim', type=int, default=0, help='partidas por pareja para estimar con el simulador (piloto contra piloto) y comparar')
    p.add_argument('--export-rows', help='guardar tus posiciones en el formato de entrenamiento de valfn.py')
    p.set_defaults(f=cmd_humanlog)
    p = sub.add_parser('matrix', help='todos contra todos del campo (y de los mazos que añadas con --also)')
    p.add_argument('--field', default=str(DEFAULT_FIELD))
    p.add_argument('--also', nargs='*', help='mazos JSON extra que entran en la tabla')
    p.add_argument('--games', type=int, default=200)
    p.add_argument('--seed', type=int, default=5)
    p.add_argument('--procs', type=int, default=DEFAULT_PROCS)
    p.set_defaults(f=cmd_matrix)


def _search_commands(sub):
    """Comandos de optimización: optimize, search, sideboard y match."""
    p = sub.add_parser('optimize', help='optimiza un mazo para 3 Legends (búsqueda local + simulación)')
    p.add_argument('--legends', nargs=3, required=True, metavar='ID')
    p.add_argument('--start', help='mazo JSON de partida (opcional)')
    p.add_argument('--field', default=str(DEFAULT_FIELD))
    p.add_argument('--iters', type=int, default=150)
    p.add_argument('--games', type=int, default=50)
    p.add_argument('--restarts', type=int, default=4)
    p.add_argument('--procs', type=int, default=DEFAULT_PROCS)
    p.add_argument('--name')
    p.add_argument('--out')
    p.set_defaults(f=cmd_optimize)
    p = sub.add_parser('search', help='busca el mejor mazo posible: criba TODAS las ternas de Legends y afina las mejores')
    p.add_argument('--field', nargs='+', default=[str(DEFAULT_FIELD)], help='uno o varios campos (JSON o carpetas)')
    p.add_argument('--screen-games', type=int, default=20, help='partidas por rival en la primera criba')
    p.add_argument('--keep', type=int, default=6, help='cuántas ternas se afinan')
    p.add_argument('--iters', type=int, default=120)
    p.add_argument('--games', type=int, default=50, help='partidas por rival al afinar')
    p.add_argument('--restarts', type=int, default=2)
    p.add_argument('--limit', type=int, default=0, help='probar solo N ternas al azar (prueba rápida)')
    p.add_argument('--procs', type=int, default=DEFAULT_PROCS)
    p.set_defaults(f=cmd_search)
    p = sub.add_parser('sideboard', help='qué meter y qué quitar contra cada rival; con --build propone un sideboard de 7')
    p.add_argument('deck')
    p.add_argument('--field', nargs='+', default=[str(DEFAULT_FIELD)])
    p.add_argument('--build', action='store_true', help='proponer un sideboard nuevo aunque el mazo ya tenga uno')
    p.add_argument('--save', action='store_true', help='guardar el sideboard propuesto en el JSON del mazo')
    p.add_argument('--games', type=int, default=100, help='partidas por cada cambio probado (sin previsión)')
    p.add_argument('--check', type=int, default=200, help='partidas de validación con previsión')
    p.add_argument('--procs', type=int, default=DEFAULT_PROCS)
    p.set_defaults(f=cmd_sideboard)
    p = sub.add_parser('match', help='enfrenta dos mazos al mejor de tres, con sideboard tras la primera partida')
    p.add_argument('deck_a')
    p.add_argument('deck_b')
    p.add_argument('--matches', type=int, default=200)
    p.add_argument('--games', type=int, default=100, help='partidas por cada cambio de sideboard probado')
    p.add_argument('--seed', type=int, default=1)
    p.add_argument('--fast', action='store_true')
    p.add_argument('--procs', type=int, default=DEFAULT_PROCS)
    p.set_defaults(f=cmd_match)


def _graph_commands(sub):
    """Comandos de la red de cartas y del razonamiento: graph, reason, learn y trios."""
    p = sub.add_parser('graph', help='red de cartas: export | card <carta> | path <A> <B> | deck <mazo.json> | build --legends ... | measure')
    p.add_argument('action', choices=['export', 'card', 'path', 'deck', 'build', 'measure'])
    p.add_argument('args', nargs='*')
    p.add_argument('--legends', nargs='+', help='3 Legends (para build, o para limitar card al pool legal)')
    p.add_argument('--core', nargs='*', help='cartas que deben ir a 3 copias (build)')
    p.add_argument('--field', nargs='+', default=[str(DEFAULT_FIELD)])
    p.add_argument('--games', type=int, default=800, help='partidas por rival al medir (sin previsión)')
    p.add_argument('--procs', type=int, default=DEFAULT_PROCS)
    p.add_argument('--name')
    p.add_argument('--out')
    p.set_defaults(f=cmd_graph)
    p = sub.add_parser('reason', help='monta un mazo razonando: condición de victoria, paquetes, tempo/valor y prueba contra el meta')
    p.add_argument('--legends', nargs=3, metavar='LEGEND', help='3 Legends (nombre o id); si faltan, las elige el plan')
    p.add_argument('--plan', help='control_dados, tempo_gosolo, gear_poder10, cuerpos_basura, gastar_y_castigar, braindance')
    p.add_argument('--core', nargs='*', help='cartas que deben ir a 3 copias')
    p.add_argument('--field', nargs='+', default=[str(DEFAULT_FIELD)])
    p.add_argument('--games', type=int, default=200, help='partidas por rival en la prueba de estrés (sin previsión)')
    p.add_argument('--heuristic', action='store_true', help='no usar los valores medidos (learn), solo las reglas a mano')
    p.add_argument('--polish', type=int, default=0, metavar='N', help='pulir después con N cambios probados en partidas (p. ej. 120)')
    p.add_argument('--name')
    p.add_argument('--out')
    p.set_defaults(f=cmd_reason)
    p = sub.add_parser('learn', help='mide con partidas cuánto vale cada carta sola y cuánto sube con lo que pide (numpy)')
    p.add_argument('--decks', type=int, default=6000, help='mazos al azar que se juegan')
    p.add_argument('--meta-games', type=int, default=6)
    p.add_argument('--pair-games', type=int, default=20)
    p.add_argument('--field', nargs='+', default=[str(DEFAULT_FIELD)])
    p.add_argument('--seed', type=int, default=1)
    p.add_argument('--procs', type=int, default=DEFAULT_PROCS)
    p.add_argument('--show', action='store_true', help='solo enseñar el modelo ya medido')
    p.set_defaults(f=cmd_learn)
    p = sub.add_parser('trios', help='ranking de ternas de Legends con la red de sinergias')
    p.add_argument('--top', type=int, default=20)
    p.add_argument('--limit', type=int, default=0, help='probar solo N ternas al azar (prueba rápida)')
    p.add_argument('--procs', type=int, default=DEFAULT_PROCS)
    p.set_defaults(f=cmd_trios)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest='cmd', required=True)
    _basic_commands(sub)
    _sim_commands(sub)
    _search_commands(sub)
    _graph_commands(sub)
    p = sub.add_parser('selftest', help='comprobación rápida de que todo funciona')
    p.set_defaults(f=cmd_selftest)
    for name in ('sim', 'gauntlet', 'explain', 'matrix', 'playbook'):
        sub.choices[name].add_argument('--fast', action='store_true', help='sin previsión: ~30 veces más rápido, juega algo peor (sobre todo control)')
    a = ap.parse_args()
    OUT.mkdir(exist_ok=True)
    set_deep(a.cmd in ('sim', 'gauntlet', 'explain', 'matrix', 'robust', 'playbook') and not getattr(a, 'fast', False))
    sys.exit(a.f(a) or 0)
